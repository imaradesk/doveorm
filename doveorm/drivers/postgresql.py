"""
DoveORM – PostgreSQL driver.

Uses ``psycopg`` (version 3) and falls back to ``psycopg2`` when only that
is installed.

Install:
    pip install "doveorm[postgres]"

Usage:
    from doveorm import PostgreSQLDatabase

    db = PostgreSQLDatabase(
        host="localhost",
        port=5432,
        user="app",
        password="secret",
        database="myapp",
    )

Behaviour
---------
* Connections run in autocommit mode so plain reads always see the latest
  committed data.  :meth:`transaction` issues ``BEGIN`` / ``COMMIT``
  explicitly; nested blocks use SAVEPOINTs.
* DDL is transactional: a migration that fails half-way is rolled back
  completely.
* INSERTs that need the new primary key use ``RETURNING`` (PostgreSQL has
  no ``lastrowid``).
* A connection that is already known to be closed is replaced before the
  next statement.  A read that loses its connection is retried once
  outside a transaction; writes are never retried (the server may already
  have applied them).
* Names that need it (reserved words, upper-case letters) are quoted, so
  ``userName`` or ``order`` work as column and table names.
* Parameters are bound client-side (like Django's default): no server-side
  prepared statements, so the driver works behind PgBouncer in transaction
  pooling mode.  Pass ``server_side_binding=True`` (psycopg 3) to opt in.
* Sessions run in UTC, matching how DoveORM stores datetimes.

Hardening defaults
------------------
* ``statement_timeout`` (seconds, optional) is enforced by the server and
  raises :class:`~doveorm.exceptions.QueryTimeout`.
* ``isolation_level`` (optional) is validated against the four SQL levels.
* ``schema`` (optional) is validated and set as the session ``search_path``.
* A warning is logged for remote connections without TLS (``sslmode``
  option) and for empty passwords.
* Serialization failures (40001), deadlocks (40P01) and lock-not-available
  (55P03) are transient, so :meth:`run_in_transaction` retries them.
* ``repr()`` never includes the password.
"""
from __future__ import annotations

import logging
from contextlib import contextmanager
from typing import Iterable, Sequence

from ..exceptions import ConfigurationError, QueryTimeout
from ..utils.sql import index_name, validate_identifier
from .base import DatabaseDriver, _DictRow

log = logging.getLogger("doveorm")

_SERIALIZATION_FAILURE = "40001"
_DEADLOCK = "40P01"
_LOCK_NOT_AVAILABLE = "55P03"
_QUERY_CANCELED = "57014"
_TRANSIENT = (_SERIALIZATION_FAILURE, _DEADLOCK, _LOCK_NOT_AVAILABLE)
_CONNECTION_CLASS = "08"          # SQLSTATE class: connection exception

ISOLATION_LEVELS = ("READ UNCOMMITTED", "READ COMMITTED", "REPEATABLE READ", "SERIALIZABLE")
LIBRARIES = ("psycopg", "psycopg2")
MAX_IDENTIFIER_LENGTH = 63        # NAMEDATALEN - 1; longer names are truncated
_LOCAL_HOSTS = ("localhost", "127.0.0.1", "::1")

_NO_DEFAULT_TYPES = ("BYTEA",)
_TEXT_TYPES = ("TEXT", "VARCHAR", "CHAR", "CHARACTER", "CITEXT")


def _load_library(name: str | None):
    """Import the requested DB-API module (or the first one available)."""
    candidates = (name,) if name else LIBRARIES
    errors = []
    for candidate in candidates:
        try:
            return __import__(candidate)
        except ImportError as exc:
            errors.append(f"{candidate}: {exc}")
    raise ImportError(
        "PostgreSQL support needs psycopg (or psycopg2): pip install \"doveorm[postgres]\" "
        f"({'; '.join(errors)})"
    )


class PostgreSQLDriver(DatabaseDriver):
    name = "postgresql"
    placeholder = "%s"
    autoincrement_sql = "GENERATED BY DEFAULT AS IDENTITY"
    backslash_escapes = False          # standard_conforming_strings is on
    supports_transactional_ddl = True
    max_limit = "ALL"
    preserve_identifier_case = True    # bare names are folded to lower case

    def __init__(
        self,
        *,
        host: str | None = None,
        port: int = 5432,
        user: str | None = None,
        password: str | None = None,
        database: str | None = None,
        schema: str | None = None,
        autoreconnect: bool = True,
        isolation_level: str | None = None,
        statement_timeout: float | None = None,
        library: str | None = None,
        server_side_binding: bool = False,
        max_lifetime: float | None = None,
        **extra_kwargs,
    ):
        super().__init__(max_lifetime=max_lifetime)
        # Where the data lives is the application's decision: never guess it.
        missing = [label for label, value in (("database", database), ("user", user)) if not value]
        if password is None:
            missing.append("password (use '' explicitly for passwordless auth)")
        if not host:
            missing.append("host (a socket directory such as /var/run/postgresql also works)")
        if missing:
            raise ConfigurationError("PostgreSQL driver is missing: " + "; ".join(missing) + ".")
        if library is not None and library not in LIBRARIES:
            raise ValueError(f"library must be one of {LIBRARIES}, got {library!r}.")
        if server_side_binding and library == "psycopg2":
            raise ConfigurationError("server_side_binding needs psycopg 3; psycopg2 always binds client-side.")
        if schema is not None:
            validate_identifier(schema, "PostgreSQL schema")
        if isolation_level is not None:
            isolation_level = " ".join(str(isolation_level).upper().replace("_", " ").split())
            if isolation_level not in ISOLATION_LEVELS:
                raise ValueError(f"isolation_level must be one of {ISOLATION_LEVELS}, got {isolation_level!r}.")
        if statement_timeout is not None:
            if isinstance(statement_timeout, bool) or float(statement_timeout) <= 0:
                raise ValueError("statement_timeout must be a positive number of seconds or None.")
            statement_timeout = float(statement_timeout)
        self.schema = schema
        self.isolation_level = isolation_level
        self.statement_timeout = statement_timeout
        self.library = library
        self.server_side_binding = bool(server_side_binding)
        self._module = None

        extra_kwargs.setdefault("connect_timeout", 10)
        extra_kwargs.setdefault("client_encoding", "UTF8")
        self._cfg = dict(
            host=host,
            port=int(port),
            user=user,
            password=password,
            dbname=database,
            **extra_kwargs,
        )
        self._database_name = database
        location = host if host.startswith("/") else f"{host}:{int(port)}"
        self._display = f"{user}@{location}/{database}"
        self.autoreconnect = autoreconnect
        if not password:
            log.warning("PostgreSQL driver configured for user %r with an empty password.", user)
        is_local = host in _LOCAL_HOSTS or host.startswith("/")
        if not is_local and "sslmode" not in extra_kwargs:
            log.warning("PostgreSQL connection to %s is not configured for TLS (pass sslmode=).", host)

    def __repr__(self):
        return f"<PostgreSQLDriver {self._display} connected={self.is_connected()}>"

    @property
    def module(self):
        """The DB-API module in use (``psycopg`` or ``psycopg2``)."""
        if self._module is None:
            self._module = _load_library(self.library)
        return self._module

    # ── connection hooks ──

    def _open(self):
        module = self.module
        cfg = dict(self._cfg)
        if module.__name__ == "psycopg":
            if not self.server_side_binding:
                cfg.setdefault("cursor_factory", module.ClientCursor)
        elif self.server_side_binding:
            raise ConfigurationError("server_side_binding needs psycopg 3; psycopg2 always binds client-side.")
        conn = module.connect(**cfg)
        try:
            conn.autocommit = True
            cur = conn.cursor()
            try:
                # DoveORM stores naive UTC datetimes; keep the session's casts consistent.
                cur.execute("SET TIME ZONE 'UTC'")
                if self.schema is not None:
                    cur.execute(f"SET search_path TO {self.schema}")       # validated identifier
                if self.statement_timeout is not None:
                    cur.execute(f"SET statement_timeout = {int(self.statement_timeout * 1000)}")
                if self.isolation_level is not None:
                    # value comes from the ISOLATION_LEVELS whitelist
                    cur.execute("SET SESSION CHARACTERISTICS AS TRANSACTION ISOLATION LEVEL "
                                f"{self.isolation_level}")
            finally:
                cur.close()
        except BaseException:
            conn.close()
            raise
        return conn

    def is_connected(self) -> bool:
        if not super().is_connected():
            return False
        return not self._conn.closed

    def _exec_control(self, conn, sql: str) -> None:
        cur = conn.cursor()
        try:
            cur.execute(sql)
        finally:
            cur.close()

    def _begin(self, conn) -> None:
        self._exec_control(conn, "BEGIN")

    def _commit(self, conn) -> None:
        self._exec_control(conn, "COMMIT")

    def _rollback(self, conn) -> None:
        if not conn.closed:
            self._exec_control(conn, "ROLLBACK")

    @property
    def integrity_errors(self):
        return (self.module.IntegrityError,)

    def is_transient_error(self, exc: BaseException) -> bool:
        return self._sqlstate(exc) in _TRANSIENT

    def _is_disconnect_error(self, exc: BaseException) -> bool:
        code = self._sqlstate(exc)
        if code is not None and code.startswith(_CONNECTION_CLASS):
            return True
        conn = self._conn
        return isinstance(exc, self.module.OperationalError) and conn is not None and bool(conn.closed)

    # ── execution helpers ──

    @staticmethod
    def _sqlstate(exc: BaseException) -> str | None:
        # psycopg 3: .sqlstate, psycopg2: .pgcode
        return getattr(exc, "sqlstate", None) or getattr(exc, "pgcode", None)

    @contextmanager
    def _translate_errors(self):
        try:
            yield
        except Exception as exc:
            if self.statement_timeout is not None and self._sqlstate(exc) == _QUERY_CANCELED:
                raise QueryTimeout(
                    f"PostgreSQL statement exceeded statement_timeout={self.statement_timeout}s."
                ) from exc
            raise

    def _run(self, fn, *, retry: bool):
        self.connect()
        if self._conn.closed and self._nesting == 0:
            # Closed by the server or the network since the last statement.
            self.disconnect()
            self.connect()
        try:
            with self._translate_errors():
                return fn(self._conn)
        except Exception as exc:
            if not (retry and self.autoreconnect and self._nesting == 0
                    and self._is_disconnect_error(exc)):
                raise
            log.warning("PostgreSQL connection lost (%s); reconnecting and retrying once.", exc)
            self.disconnect(force=True)
            self.connect()
            with self._translate_errors():
                return fn(self._conn)

    def _prepare(self, sql: str, params: Sequence | None):
        params = self._params(params)
        if params:
            return self.adapt_sql(sql), params
        return sql, None          # None → the driver does not %-format the query

    # ── query execution ──

    def execute(self, sql: str, params: Sequence | None = None) -> list:
        query, args = self._prepare(sql, params)

        def run(conn):
            cur = conn.cursor()
            try:
                cur.execute(query, args)
                if cur.description is None:
                    return []
                col_names = [desc[0] for desc in cur.description]
                return [_DictRow(col_names, row) for row in cur.fetchall()]
            finally:
                cur.close()

        return self._run(run, retry=True)

    def execute_write(self, sql: str, params: Sequence | None = None) -> int:
        """Run INSERT/UPDATE/DELETE.

        INSERTs return the first column of the ``RETURNING`` row (see
        :meth:`returning_sql`), or ``None`` without one.
        """
        query, args = self._prepare(sql, params)
        is_insert = self._is_insert(sql)

        def run(conn):
            cur = conn.cursor()
            try:
                cur.execute(query, args)
                if not is_insert:
                    return cur.rowcount
                if cur.description is None:
                    return None
                row = cur.fetchone()
                return row[0] if row else None
            finally:
                cur.close()

        return self._run(run, retry=False)

    def execute_many(self, sql: str, seq_of_params: Iterable[Sequence]) -> int:
        rows = [self._params(p) for p in seq_of_params]
        if not rows:
            return 0
        query = self.adapt_sql(sql)
        with self.transaction() as conn, self._translate_errors():
            cur = conn.cursor()
            try:
                cur.executemany(query, rows)
                return cur.rowcount
            finally:
                cur.close()

    def _execute_statement(self, sql: str) -> None:
        def run(conn):
            cur = conn.cursor()
            try:
                cur.execute(sql)
            finally:
                cur.close()

        self._run(run, retry=False)

    # ── introspection ──

    def table_exists(self, table_name: str) -> bool:
        rows = self.execute(
            "SELECT 1 FROM pg_catalog.pg_tables "
            "WHERE schemaname = current_schema() AND tablename = ?",
            [self.stored_name(table_name)],
        )
        return len(rows) > 0

    def index_exists(self, table_name: str, index: str) -> bool:
        validate_identifier(index, "index name")
        rows = self.execute(
            "SELECT 1 FROM pg_catalog.pg_indexes "
            "WHERE schemaname = current_schema() AND tablename = ? AND indexname = ?",
            [self.stored_name(table_name), self.stored_name(index)],
        )
        return len(rows) > 0

    def stored_name(self, name: str) -> str:
        """How PostgreSQL stores *name*: folded unless quoted, cut to 63 bytes."""
        stored = name if self.quote_name(name) != name else name.lower()
        return stored.encode("utf-8")[:MAX_IDENTIFIER_LENGTH].decode("utf-8", "ignore")

    def create_index(self, table, columns, *, unique=False, name=None) -> str:
        validate_identifier(table, "table name")
        for col in columns:
            validate_identifier(col, "index column")
        if name is None:
            name = index_name("uq" if unique else "idx", table, columns)
        validate_identifier(name, "index name")
        kind = "UNIQUE INDEX" if unique else "INDEX"
        qn = self.quote_name
        self._execute_statement(
            f"CREATE {kind} IF NOT EXISTS {qn(name)} ON {qn(table)} ({', '.join(qn(c) for c in columns)})"
        )
        return name

    # ── dialect overrides ──

    def insert_ignore_prefix(self) -> str:
        return "INSERT"

    def insert_ignore_suffix(self) -> str:
        return " ON CONFLICT DO NOTHING"

    def returning_sql(self, pk: str) -> str:
        return f" RETURNING {self.quote_name(pk)}"

    def lookup_cast(self, column_sql: str, field, lookup: str) -> str:
        sql_type = field._resolved_type(self).split("(", 1)[0].strip().upper()
        if sql_type in _TEXT_TYPES:
            return column_sql
        if sql_type == "UUID":
            # Match the 32-char hex form DoveORM uses for UUIDs everywhere.
            return f"REPLACE(CAST({column_sql} AS TEXT), '-', '')"
        return f"CAST({column_sql} AS TEXT)"

    def sync_auto_increment(self, table: str, pk: str, value) -> None:
        if isinstance(value, bool) or not isinstance(value, int) or value < 1:
            return
        # Identity sequences ignore explicit keys; move the sequence past *value*
        # (never backwards) so later generated keys do not collide with it.
        self.execute(
            "SELECT setval(seq, ?) FROM (SELECT pg_get_serial_sequence(?, ?)::regclass AS seq) s "
            "WHERE seq IS NOT NULL AND ? > COALESCE(pg_sequence_last_value(seq), 0)",
            [value, self.quote_name(table), self.stored_name(pk), value],
        )

    def foreign_key_pragma(self) -> str | None:
        return None  # PostgreSQL always enforces foreign keys

    def allows_default_for(self, sql_type: str) -> bool:
        base = sql_type.split("(", 1)[0].strip().upper()
        return base not in _NO_DEFAULT_TYPES

    def sql_type_map(self) -> dict[str, str]:
        return {
            "INTEGER":  "INTEGER",
            "BIGINT":   "BIGINT",
            "SMALLINT": "SMALLINT",
            "REAL":     "DOUBLE PRECISION",
            "DECIMAL":  "NUMERIC",
            "TEXT":     "TEXT",
            "VARCHAR":  "VARCHAR",
            "BOOLEAN":  "SMALLINT",      # 0/1, like SQLite and MySQL's TINYINT(1)
            "DATETIME": "TIMESTAMP",
            "DATE":     "DATE",
            "TIME":     "TIME",
            "JSON":     "JSONB",
            "UUID":     "UUID",
            "BLOB":     "BYTEA",
        }

    def autoincrement_definition(self) -> str:
        return "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
