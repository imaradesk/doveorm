        s = Student.create(name="Sam")
        c1, c2 = Course.create(title="Math"), Course.create(title="Art")
        s.courses.add(c1, c2)
        s.courses.add(c1)                             # duplicate is ignored
        self.assertEqual(self.db.execute("SELECT COUNT(*) FROM student_courses")[0][0], 2)
