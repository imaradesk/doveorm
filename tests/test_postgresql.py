class TestDriverUnit(unittest.TestCase):
    def test_dialect(self):
        drv = PostgreSQLDriver(host="localhost", user="u", password="", database="d")
        self.assertEqual(drv.name, "postgresql")
        self.assertEqual(drv.placeholder, "%s")
        self.assertEqual(drv.adapt_sql("SELECT * FROM t WHERE a = ? AND b LIKE '50%'"),
                         "SELECT * FROM t WHERE a = %s AND b LIKE '50%%'")
        self.assertEqual(drv.limit_offset_sql(None, 5), "LIMIT ALL OFFSET 5")
        self.assertEqual(drv.insert_ignore_prefix(), "INSERT")
        self.assertEqual(drv.insert_ignore_suffix(), " ON CONFLICT DO NOTHING")
        self.assertEqual(drv.returning_sql("id"), " RETURNING id")
        self.assertTrue(drv.supports_transactional_ddl)
        self.assertFalse(drv.backslash_escapes)

    def test_field_types(self):
        drv = offline_db().driver
        cases = [
            (F.AutoField(), "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
            (F.BigAutoField(), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
            (F.CharField(max_length=40, nullable=False), "VARCHAR(40) NOT NULL"),
            (F.TextField(), "TEXT"),
            (F.FloatField(), "DOUBLE PRECISION"),
            (F.DecimalField(max_digits=8, decimal_places=3), "NUMERIC(8,3)"),
            (F.BooleanField(default=True), "SMALLINT DEFAULT 1"),
            (F.DateTimeField(), "TIMESTAMP"),
            (F.DateField(), "DATE"),
            (F.TimeField(), "TIME"),
            (F.DurationField(), "BIGINT"),
            (F.UUIDField(), "UUID"),
            (F.JSONField(), "JSONB"),
            (F.BinaryField(default=b"x"), "BYTEA"),   # bytea DEFAULT literals are not rendered
        ]
        for field, expected in cases:
            with self.subTest(field=type(field).__name__):
                self.assertEqual(field.sql_definition(drv), expected)

    def test_missing_settings(self):
        with self.assertRaises(ConfigurationError) as ctx:
            PostgreSQLDriver(user="u", database="d")
        msg = str(ctx.exception)
        self.assertIn("password", msg)
        self.assertIn("host", msg)

    def test_repr_hides_password(self):
        drv = PostgreSQLDriver(host="127.0.0.1", user="app", password="s3cret", database="d")
        self.assertIn("app@127.0.0.1:5432/d", repr(drv))
        self.assertNotIn("s3cret", repr(drv))

    def test_socket_directory_host(self):
        drv = PostgreSQLDriver(host="/var/run/postgresql", user="app", password="", database="d")
        self.assertIn("app@/var/run/postgresql/d", repr(drv))

    def test_tls_warning_for_remote_host(self):
        with self.assertLogs("doveorm", "WARNING") as logs:
            PostgreSQLDriver(host="db.example.com", user="u", password="p", database="d")
        self.assertTrue(any("TLS" in line for line in logs.output))

    def test_validation(self):
        kw = dict(host="localhost", user="u", password="p", database="d")
        with self.assertRaises(ValueError):
            PostgreSQLDriver(isolation_level="SNAPSHOT", **kw)
        with self.assertRaises(ValueError):
            PostgreSQLDriver(schema="public; DROP TABLE x", **kw)
        with self.assertRaises(ValueError):
            PostgreSQLDriver(statement_timeout=0, **kw)
        with self.assertRaises(ValueError):
            PostgreSQLDriver(library="pg8000", **kw)
        drv = PostgreSQLDriver(isolation_level="repeatable_read", **kw)
        self.assertEqual(drv.isolation_level, "REPEATABLE READ")

    def test_cannot_pickle(self):
        import pickle
        with self.assertRaises(TypeError):
            pickle.dumps(offline_db())


