class _ServerMixin:
    LIBRARY = None
    OPTIONS = {}

    @classmethod
    def setUpClass(cls):
        if not HAVE_SERVER:
            raise unittest.SkipTest("set DOVEORM_TEST_PG_HOST / _USER / _NAME to run")
        if not _installed(cls.LIBRARY):
            raise unittest.SkipTest(f"{cls.LIBRARY} is not installed")
        cls.schema = f"doveorm_t_{uuid.uuid4().hex[:10]}"
        admin = PostgreSQLDatabase(**PG_ENV, library=cls.LIBRARY)
        admin.execute_ddl(f"CREATE SCHEMA {cls.schema}")
        admin.close_all()

    @classmethod
    def tearDownClass(cls):
        admin = PostgreSQLDatabase(**PG_ENV, library=cls.LIBRARY)
        admin.execute_ddl(f"DROP SCHEMA IF EXISTS {cls.schema} CASCADE")
        admin.close_all()

    def setUp(self):
        super().setUp()
        self._registry = dict(ModelMeta._registry)
        self.db = self.connect()
        self.db.execute_script(f"DROP SCHEMA {self.schema} CASCADE; CREATE SCHEMA {self.schema}")

    def tearDown(self):
        self.db.close_all()
        ModelMeta._registry.clear()
        ModelMeta._registry.update(self._registry)
        super().tearDown()

    def connect(self, **kwargs):
        return PostgreSQLDatabase(**PG_ENV, library=self.LIBRARY, schema=self.schema,
                                  **{**self.OPTIONS, **kwargs})

    def define(self, name, attrs, meta=None):
        ModelMeta._registry.pop(name, None)
        ns = dict(attrs)
        ns["__module__"] = __name__
        if meta:
            ns["Meta"] = type("Meta", (), meta)
        cls = ModelMeta(name, (Model,), ns)
        cls.use(self.db)
        return cls


class _ORMTests(_ServerMixin):
    def everything_model(self):
        return self.define("Thing", {
            "id": F.AutoField(),
            "name": F.CharField(max_length=50, nullable=False, unique=True),
            "body": F.TextField(nullable=True),
            "count": F.IntegerField(default=0),
            "big": F.BigIntegerField(nullable=True),
            "ratio": F.FloatField(nullable=True),
            "price": F.DecimalField(max_digits=8, decimal_places=2, nullable=True),
            "active": F.BooleanField(default=True),
            "born": F.DateField(nullable=True),
            "seen": F.DateTimeField(nullable=True),
            "alarm": F.TimeField(nullable=True),
            "span": F.DurationField(nullable=True),
            "token": F.UUIDField(nullable=True),
            "meta": F.JSONField(nullable=True),
            "blob": F.BinaryField(nullable=True),
        })

    def test_round_trip_every_type(self):
        Thing = self.everything_model()
        Thing.create_table()
        token = uuid.uuid4()
        values = dict(
            name="a", body="long 'quoted' text \\ with backslash", count=3, big=2 ** 40,
            ratio=0.25, price=decimal.Decimal("12.50"), active=False,
            born=datetime.date(2001, 2, 3), seen=datetime.datetime(2024, 5, 6, 7, 8, 9, 123456),
            alarm=datetime.time(6, 30, 15), span=datetime.timedelta(days=1, microseconds=5),
            token=token, meta={"tags": ["x", "y"], "n": 1}, blob=b"\x00\x01binary",
        )
        t = Thing.create(**values)
        self.assertEqual(t.id, 1)
        loaded = Thing.where(id=t.id).first()
        for key, expected in values.items():
            with self.subTest(field=key):
                self.assertEqual(getattr(loaded, key), expected)
        self.assertEqual(Thing.create(name="b").id, 2)

    def test_queries(self):
        Thing = self.everything_model()
        Thing.create_table()
        for i, name in enumerate(["Alpha", "beta", "Gamma", "50% off", "under_score"]):
            Thing.create(name=name, count=i, active=i % 2 == 0, price=decimal.Decimal(i))
        self.assertEqual(Thing.where().count(), 5)
        self.assertEqual(Thing.where(name__iexact="ALPHA").first().name, "Alpha")
        self.assertEqual(Thing.where(name__contains="a").count(), 3)    # Alpha, beta, Gamma
        self.assertEqual(Thing.where(name__contains="A").count(), 1)    # LIKE is case-sensitive
        self.assertEqual(Thing.where(name__icontains="A").count(), 3)
        self.assertEqual([t.name for t in Thing.where(name__contains="%").get()], ["50% off"])
        self.assertEqual([t.name for t in Thing.where(name__contains="_").get()], ["under_score"])
        self.assertEqual(Thing.where(active=True).count(), 3)
        self.assertEqual(Thing.where(count__gte=2, count__lt=4).count(), 2)
        self.assertEqual(Thing.where(count__in=[0, 4]).count(), 2)
        self.assertEqual(Thing.where(body__isnull=True).count(), 5)
        self.assertEqual(Thing.where(price__gt=decimal.Decimal("2.5")).count(), 2)
        names = [t.name for t in Thing.where().order_by("-count").offset(1).limit(2).get()]
        self.assertEqual(names, ["50% off", "Gamma"])
        self.assertEqual([t.count for t in Thing.where().order_by("count").offset(3).get()], [3, 4])
        self.assertTrue(Thing.where(name="beta").exists())
        self.assertEqual(Thing.where(active=False).update(body="odd"), 2)
        self.assertEqual(Thing.where(body="odd").delete(), 2)
        rows = self.db.raw("SELECT name FROM things WHERE name LIKE ? ORDER BY name", ["%a"])
        self.assertEqual([r["name"] for r in rows], ["Alpha", "Gamma"])

    def test_unique_violation_and_get_or_create(self):
        Thing = self.everything_model()
        Thing.create_table()
        Thing.create(name="dup")
